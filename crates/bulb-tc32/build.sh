#!/bin/sh
# Build the Rust firmware for the TLSR8258 (TC32 core).
#
# Stock rustc has no TC32 backend, and TC32 runs ARMv4T Thumb-1 code in its
# own encoding. So rustc only goes as far as LLVM bitcode for thumbv4t, and
# the llvm-tc32 fork (clang/lld with -mcpu=tc32) generates the TC32 code:
#
#   cargo (build-std, -C linker-plugin-lto,
#          --emit=llvm-bc)                   ->  bitcode of every crate
#   llvm-link                                ->  one module
#   llvm-dis + sed                           ->  every function's CPU = tc32,
#                                                no jump tables
#   clang -mcpu=tc32 -Oz                     ->  TC32 object
#   clang -mcpu=tc32 boot/start.S            ->  TC32 object
#   ld.lld -T boot/link.ld --gc-sections     ->  ELF
#   tc32-devtools elf2bin.py                 ->  flash image
#   ota-packer                               ->  image with CRC, Zigbee .ota file
#
# Variables:
#   BOARD              the bulb the image is for: product and hardware revision
#                      (boards.tsv, generated by emulator/gen_boards.py from the
#                      stock firmware's profiles, docs/stock-profiles.md), e.g.
#                      EGLO_ZM_TW-4.62. Pins, PWM channels, colour temperature
#                      range, identity and OTA image type are the board's
#   VARIANT            without BOARD: dimm (default, ESMLFzm_w6_Dimm-4.63) or tw
#                      (ESMLFzm_w6_TW-4.63), the filament bulbs
#   BLE                1 (default): Bluetooth LE next to Zigbee, the stock bulb's
#                      profile (AwoX app, update over BLE). 0: Zigbee only,
#                      output directory with the suffix -noble
#   TRACE              1: diagnostics for the emulator's test harness (the
#                      `trace` feature: a ring of what became of every frame,
#                      ZB_TRACE); output directory with the suffix -trace.
#                      Not for the bulbs
#   BULB_FILE_VERSION  OTA file version of the build, hexadecimal (default 00020000)
#   OUT_DIR            output directory (default as below)
#   TOUCHLINK_MASTER_KEY  the touchlink master key, 32 hexadecimal digits: the
#                      image then offers and accepts key index 4 (what commercial
#                      touchlink initiators use). Not in this repository; without
#                      it the image has key indices 0 and 15 only.
#
# Needs:
#   TC32_LLVM      bin directory of a built llvm-tc32
#                  (default ~/oss/llvm-tc32/build/bin)
#   TC32_DEVTOOLS  checkout of goyamamoto/tc32-devtools (default ~/oss/tc32-devtools)
#   RUST_LIB_SRC   the Rust standard library sources of the installed rustc,
#                  for build-std (default: nixpkgs#rustPlatform.rustLibSrc, or
#                  the rust-src component in the sysroot)
# rustc is the stable one; RUSTC_BOOTSTRAP=1 lets it take build-std.
#
# Output in target/tc32 (target/tc32-tw for the TW filament bulb, target/tc32-<board>
# in lower case for the others): bulb-tc32.elf, .bin
# (the image as linked), bulb-tc32-ota.bin (with size and CRC: what goes into
# the OTA staging area) and bulb-tc32.ota (Zigbee OTA file).
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
llvm=${TC32_LLVM:-$HOME/oss/llvm-tc32/build/bin}
devtools=${TC32_DEVTOOLS:-$HOME/oss/tc32-devtools}
variant=${VARIANT:-dimm}
version=${BULB_FILE_VERSION:-00020000}
case "${BLE:-1}" in
    1) ble=ble; suffix= ;;
    0) ble=; suffix=-noble ;;
    *) echo "build.sh: BLE must be 0 or 1" >&2; exit 1 ;;
esac
case "${TRACE:-0}" in
    1) ble="${ble:+$ble,}trace"; suffix=$suffix-trace ;;
    0) ;;
    *) echo "build.sh: TRACE must be 0 or 1" >&2; exit 1 ;;
esac
board=${BOARD:-}
if [ -z "$board" ]; then
    case "$variant" in
        dimm) board=ESMLFzm_w6_Dimm-4.63 ;;
        tw) board=ESMLFzm_w6_TW-4.63 ;;
        *) echo "build.sh: unknown VARIANT '$variant' (dimm|tw; other bulbs: BOARD=)" >&2; exit 1 ;;
    esac
fi
line=$(awk -F '\t' -v b="$board" '$1 == b' "$here/boards.tsv")
if [ -z "$line" ]; then
    echo "build.sh: unknown BOARD '$board'; the boards:" >&2
    grep -v '^#' "$here/boards.tsv" | cut -f1 | sed 's/^/    /' >&2
    exit 1
fi
image_type=$(printf '%s\n' "$line" | cut -f3)
case "$board" in
    ESMLFzm_w6_Dimm-4.63) dir=tc32 ;;
    ESMLFzm_w6_TW-4.63) dir=tc32-tw ;;
    *) dir=tc32-$(printf '%s' "$board" | tr 'A-Z' 'a-z') ;;
esac
out=${OUT_DIR:-$root/target/$dir$suffix}
features="--no-default-features --features=$ble,"
target=thumbv4t-none-eabi

[ -x "$llvm/clang" ] || { echo "build.sh: no clang in $llvm (set TC32_LLVM)" >&2; exit 1; }
[ -f "$devtools/compiler/elf2bin.py" ] || { echo "build.sh: no tc32-devtools in $devtools (set TC32_DEVTOOLS)" >&2; exit 1; }

if [ -z "${RUST_LIB_SRC:-}" ]; then
    sysroot_src=$(rustc --print sysroot)/lib/rustlib/src/rust/library
    if [ -d "$sysroot_src/core" ]; then
        RUST_LIB_SRC=$sysroot_src
    else
        RUST_LIB_SRC=$(nix build --no-link --print-out-paths nixpkgs#rustPlatform.rustLibSrc)
    fi
fi

mkdir -p "$out"
rm -rf "$out/bc"
mkdir -p "$out/bc"

if [ -n "${TOUCHLINK_MASTER_KEY:-}" ]; then
    export TOUCHLINK_MASTER_KEY
    echo "== touchlink: key index 4 enabled (key given to the build)"
else
    unset TOUCHLINK_MASTER_KEY
    echo "== touchlink: no master key (key indices 0 and 15 only)"
fi

# (source paths in panic locations relative, so that an image does not depend on
# where it was built)
echo "== rustc -> bitcode ($target, board $board, OTA image type $image_type, version $version)"
(cd "$here" && RUSTC_BOOTSTRAP=1 __CARGO_TESTS_ONLY_SRC_ROOT="$RUST_LIB_SRC" BULB_FILE_VERSION="$version" BULB_BOARD="$board" \
    RUSTFLAGS="-C linker-plugin-lto -C force-frame-pointers=no --emit=llvm-bc --remap-path-prefix=$HOME=~ --remap-path-prefix=$RUST_LIB_SRC=rust --remap-path-prefix=$root=outglow" CARGO_TARGET_DIR="$out/cargo" \
    cargo build --release --target "$target" $features \
        -Zbuild-std=core -Zbuild-std-features=compiler-builtins-mem)

echo "== bitcode -> TC32 object (llvm-tc32 $("$llvm/clang" --version | head -1))"
(cd "$out/bc" && "$llvm/llvm-ar" x "$out/cargo/$target/release/libbulb_tc32.a")
# With -C linker-plugin-lto the library's members are bitcode, except those of
# compiler_builtins, which rustc always compiles to machine code (Thumb here).
# For such a member take the crate's bitcode that --emit=llvm-bc left beside
# the rlib (same name and hash).
modules=
for member in "$out"/bc/*.o; do
    if [ "$(head -c 2 "$member")" = BC ]; then
        modules="$modules $member"
        continue
    fi
    crate=$(basename "$member" | cut -d. -f1)
    bc=$out/cargo/$target/release/deps/$crate.bc
    [ -f "$bc" ] || { echo "build.sh: $member is machine code and $bc does not exist" >&2; exit 1; }
    case " $modules " in *" $bc "*) ;; *) modules="$modules $bc" ;; esac
done
"$llvm/llvm-link" $modules -o "$out/rust.bc"
"$llvm/llvm-dis" "$out/rust.bc" -o "$out/rust.thumb.ll"
# rustc names its own CPU for the target in every function's attributes, and
# those win over clang's -mcpu. Jump tables are off as for all TC32 code
# (tc32-devtools' README: a table dispatch reads PC in a way no vendor code does).
sed 's/"target-cpu"="[^"]*"/"no-jump-tables"="true" "target-cpu"="tc32"/' \
    "$out/rust.thumb.ll" > "$out/rust.ll"
if grep '"target-cpu"=' "$out/rust.ll" | grep -qv '"target-cpu"="tc32"' || ! grep -q '"target-cpu"="tc32"' "$out/rust.ll"; then
    echo "build.sh: could not retarget the bitcode to tc32" >&2
    exit 1
fi

cflags="--target=$target -mcpu=tc32 -mthumb -mfloat-abi=soft"
"$llvm/clang" $cflags -Oz -ffunction-sections -fdata-sections \
    -mllvm -arm-load-store-opt=false -Wno-override-module \
    -c "$out/rust.ll" -o "$out/rust.o"
"$llvm/clang" $cflags -DIMAGE_TYPE=$image_type -c "$here/boot/start.S" -o "$out/start.o"

echo "== link"
"$llvm/ld.lld" -T "$here/boot/link.ld" --gc-sections -Map="$out/bulb-tc32.map" \
    "$out/start.o" "$out/rust.o" -o "$out/bulb-tc32.elf"
python3 "$devtools/compiler/elf2bin.py" "$out/bulb-tc32.elf" "$out/bulb-tc32.bin"
"$llvm/llvm-size" "$out/bulb-tc32.elf"

echo "== OTA image"
cp -f "$out/bulb-tc32.bin" "$out/bulb-tc32-ota.bin"
python3 "$root/ota-packer/telink_image.py" "$out/bulb-tc32-ota.bin"
python3 "$root/ota-packer/zigbee_ota.py" "$out/bulb-tc32-ota.bin" -o "$out/bulb-tc32.ota" \
    --manufacturer-code 0x1141 --image-type $image_type --file-version "0x$version" \
    --header-string "eglo-rs $board"
ls -l "$out/bulb-tc32.bin" "$out/bulb-tc32-ota.bin" "$out/bulb-tc32.ota"
